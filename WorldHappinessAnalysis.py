"""## **7. Regression Analysis**

GDP Model
"""

model_data_1 = df_clean[
    [
        "Score",
        "GDP per Capita"
    ]
].dropna()

X = model_data_1[["GDP per Capita"]]
y = model_data_1["Score"]

model_1 = LinearRegression()

model_1.fit(X, y)

predictions_1 = model_1.predict(X)

r2_model_1 = r2_score(
    y,
    predictions_1
)

print("Model 1 R²:", round(r2_model_1, 4))
print("GDP coefficient:", model_1.coef_[0])
print("Intercept:", model_1.intercept_)

"""Socioeconomic model"""

